def explain(row_df):
    x = pre.transform(row_df[FEATS])[0]
    contrib = COEF * (x - MU)
    by = pd.Series(contrib).groupby(GROUP).sum()
    logit = BASE_LOGIT + by.sum()
    return by.sort_values(key=np.abs, ascending=False), logit


def score(row_df):
    return float(model.predict_proba(row_df[FEATS])[0, 1])



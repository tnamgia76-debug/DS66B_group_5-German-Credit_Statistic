def encode_category_values(frame):
    """Accept either original integer codes or the labels shown in the form."""
    encoded = frame.copy()
    problems = []
    for feature in CATEGORICAL_FEATURES:
        if feature not in encoded:
            continue
        label_to_code = {label.casefold(): code
                         for code, label in LABELS.get(feature, {}).items()}

        def convert(value):
            if pd.isna(value):
                return value
            if isinstance(value, str):
                stripped = value.strip()
                if stripped.casefold() in label_to_code:
                    return label_to_code[stripped.casefold()]
                try:
                    return int(float(stripped))
                except ValueError:
                    return value
            return value

        encoded[feature] = encoded[feature].map(convert)
        allowed = {int(v) for v in CATV.get(feature, [])}
        invalid = ~encoded[feature].isin(allowed) & encoded[feature].notna()
        if invalid.any():
            examples = encoded.loc[invalid, feature].astype(str).unique()[:3].tolist()
            problems.append(f"{feature}: {examples}")
    if problems:
        raise ValueError("Giá trị categorical không nhận diện được: " + "; ".join(problems))
    return encoded



# ---------------------------------------------------------------- helpers
def conf(y, pred):
    y, pred = np.asarray(y), np.asarray(pred)
    tn = int(((y == 0) & (pred == 0)).sum()); fp = int(((y == 0) & (pred == 1)).sum())
    fn = int(((y == 1) & (pred == 0)).sum()); tp = int(((y == 1) & (pred == 1)).sum())
    return tn, fp, fn, tp


def cost(fn, fp, fn_cost=FN_COST):
    return fn_cost * fn + FP_COST * fp


def metrics(y, prob, pred):
    tn, fp, fn, tp = conf(y, pred)
    n = len(y)
    out = dict(n=n, tn=tn, fp=fp, fn=fn, tp=tp, cost=cost(fn, fp), cost100=100 * cost(fn, fp) / n,
               accuracy=(tn + tp) / n, recall=tp / max(tp + fn, 1), precision=tp / max(tp + fp, 1),
               specificity=tn / max(tn + fp, 1))
    p, r = out["precision"], out["recall"]
    out["f1"] = 2 * p * r / (p + r) if p + r else 0.0
    if prob is not None and len(set(y)) == 2:
        out["auc"] = roc_auc_score(y, prob); out["ap"] = average_precision_score(y, prob)
        out["brier"] = brier_score_loss(y, prob)
    return out


@st.cache_data
def boot_cost100(actual, pred, n=2000, seed=42):
    rng = np.random.default_rng(seed)
    actual, pred = np.asarray(actual), np.asarray(pred)
    idx = rng.integers(0, len(actual), (n, len(actual)))
    a, p = actual[idx], pred[idx]
    fn = ((a == 1) & (p == 0)).sum(1); fp = ((a == 0) & (p == 1)).sum(1)
    return 100 * (FN_COST * fn + fp) / len(actual)


@st.cache_data
def paired_boot(actual, pred_a, pred_b, n=4000, seed=42):
    rng = np.random.default_rng(seed)
    actual, pa, pb = map(np.asarray, (actual, pred_a, pred_b))
    idx = rng.integers(0, len(actual), (n, len(actual)))
    def c(p):
        a, q = actual[idx], p[idx]
        return 100 * (FN_COST * ((a == 1) & (q == 0)).sum(1) + ((a == 0) & (q == 1)).sum(1)) / len(actual)
    return c(pa) - c(pb)


def build_pipeline(features):
    num = [f for f in features if f in NUMERIC]
    cat = [f for f in features if f not in NUMERIC]
    pre = ColumnTransformer([
        ("num", Pipeline([("imp", SimpleImputer(strategy="median")), ("sc", StandardScaler())]), num),
        ("cat", Pipeline([("imp", SimpleImputer(strategy="most_frequent")),
                          ("oh", OneHotEncoder(handle_unknown="ignore", sparse_output=False))]), cat)])
    return Pipeline([("preprocessor", pre),
                     ("classifier", LogisticRegression(C=0.1, class_weight="balanced", max_iter=1000,
                                                       random_state=42))])


@st.cache_data
def frozen_rule_cv():
    """Frozen rule (Top-14 LR C=0.1 balanced) refit on 4 of 5 outer folds of Development -> OOF P(Bad).
    The rule was *chosen* using these data, so this is optimistic; nested CV is the honest estimate."""
    f640 = SUM.get("features_640") or FEATS
    d = dev.merge(folds, on="Id")
    oof = pd.Series(index=d.index, dtype=float)
    for k in sorted(d["outer_validation_fold"].unique()):
        tr, va = d[d["outer_validation_fold"] != k], d[d["outer_validation_fold"] == k]
        pipe = build_pipeline(f640).fit(tr[f640], tr["bad_credit"])
        oof.loc[va.index] = pipe.predict_proba(va[f640])[:, 1]
    return d["Id"].values, d["bad_credit"].values, oof.values


